#include "libft.h"

void	ft_putendl_fd(char *s, int fd)
{
	char	c;
	char	n_line;

	n_line = '\n';
	while (*s)
	{
		c = *s++;
		write(fd, &c, 1);
	}
	write(fd, &n_line, 1);
}
